-- 1. Habilitar extensões necessárias caso ainda não existam
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "unaccent";

-- 2. TABELA: cursos (Catálogo institucional de cursos / módulos)
CREATE TABLE IF NOT EXISTS public.cursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    descricao TEXT,
    ativo BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT cursos_nome_unique UNIQUE (nome)
);

-- Índices para busca rápida no catálogo e autocomplete
CREATE INDEX IF NOT EXISTS idx_cursos_nome ON public.cursos (nome);
CREATE INDEX IF NOT EXISTS idx_cursos_ativo ON public.cursos (ativo);

-- 3. TABELA: fichas (Fichas pedagógicas e cadastrais dos alunos)
CREATE TABLE IF NOT EXISTS public.fichas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricula VARCHAR(50) NOT NULL,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    data_nascimento DATE,
    telefone VARCHAR(50),
    instrutor VARCHAR(255),
    data_inicio_curso DATE,
    data_termino_curso DATE,
    data_linha_vida DATE,
    data_form1 DATE,
    data_form2 DATE,
    data_dreamday DATE,
    data_fechamento1 DATE,
    data_fechamento2 DATE,
    data_fechamento3 DATE,
    dia_semana VARCHAR(50),
    horario_inicio VARCHAR(20),
    horario_fim VARCHAR(20),
    unit_id UUID DEFAULT 'a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11',
    observacoes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fichas_matricula_unique UNIQUE (matricula)
);

-- Índices para buscas na listagem, filtros e autocompletes
CREATE INDEX IF NOT EXISTS idx_fichas_matricula ON public.fichas (matricula);
CREATE INDEX IF NOT EXISTS idx_fichas_nome ON public.fichas (nome);
CREATE INDEX IF NOT EXISTS idx_fichas_instrutor ON public.fichas (instrutor);
CREATE INDEX IF NOT EXISTS idx_fichas_created_at ON public.fichas (created_at DESC);

-- Vínculo opcional com a tabela units se existente no ambiente compartilhado
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.tables 
        WHERE table_schema = 'public' AND table_name = 'units'
    ) THEN
        IF NOT EXISTS (
            SELECT 1 FROM information_schema.table_constraints 
            WHERE constraint_name = 'fk_fichas_unit'
        ) THEN
            ALTER TABLE public.fichas 
            ADD CONSTRAINT fk_fichas_unit 
            FOREIGN KEY (unit_id) REFERENCES public.units(id) ON DELETE SET NULL;
        END IF;
    END IF;
END $$;

-- 4. TABELA: fichas_cursos (Relacionamento aluno-curso com ordenação didática)
CREATE TABLE IF NOT EXISTS public.fichas_cursos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ficha_id BIGINT NOT NULL REFERENCES public.fichas(id) ON DELETE CASCADE,
    curso_id BIGINT NOT NULL REFERENCES public.cursos(id) ON DELETE RESTRICT,
    curso_nome VARCHAR(255) NOT NULL,
    ordem INTEGER NOT NULL CHECK (ordem >= 1 AND ordem <= 18),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fichas_cursos_ficha_ordem_unique UNIQUE (ficha_id, ordem)
);

-- Índices para joins e montagem da ficha completa
CREATE INDEX IF NOT EXISTS idx_fichas_cursos_ficha_id ON public.fichas_cursos (ficha_id);
CREATE INDEX IF NOT EXISTS idx_fichas_cursos_curso_id ON public.fichas_cursos (curso_id);
CREATE INDEX IF NOT EXISTS idx_fichas_cursos_ficha_ordem ON public.fichas_cursos (ficha_id, ordem ASC);

-- 5. TRIGGER: Atualização automática da coluna updated_at
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS set_cursos_updated_at ON public.cursos;
CREATE TRIGGER set_cursos_updated_at
    BEFORE UPDATE ON public.cursos
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_updated_at();

DROP TRIGGER IF EXISTS set_fichas_updated_at ON public.fichas;
CREATE TRIGGER set_fichas_updated_at
    BEFORE UPDATE ON public.fichas
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_updated_at();

DROP TRIGGER IF EXISTS set_fichas_cursos_updated_at ON public.fichas_cursos;
CREATE TRIGGER set_fichas_cursos_updated_at
    BEFORE UPDATE ON public.fichas_cursos
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_updated_at();

-- 6. POLÍTICAS RLS (Row Level Security) - Padrão Gestão de Apostilas (Acesso público para anon e authenticated)
ALTER TABLE public.cursos ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Acesso total a cursos para anon e authenticated" ON public.cursos;
CREATE POLICY "Acesso total a cursos para anon e authenticated"
ON public.cursos FOR ALL TO anon, authenticated
USING (true) WITH CHECK (true);

ALTER TABLE public.fichas ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Acesso total a fichas para anon e authenticated" ON public.fichas;
CREATE POLICY "Acesso total a fichas para anon e authenticated"
ON public.fichas FOR ALL TO anon, authenticated
USING (true) WITH CHECK (true);

ALTER TABLE public.fichas_cursos ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Acesso total a fichas_cursos para anon e authenticated" ON public.fichas_cursos;
CREATE POLICY "Acesso total a fichas_cursos para anon e authenticated"
ON public.fichas_cursos FOR ALL TO anon, authenticated
USING (true) WITH CHECK (true);
